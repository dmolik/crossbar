#!/usr/bin/env python3

# Manifest V3: generate the service worker from background.html, so that both
# load the exact same scripts in the exact same order.

import os
import re
import sys

if len(sys.argv) == 1 or not sys.argv[1]:
    raise SystemExit('Build dir missing.')

build_dir = os.path.abspath(sys.argv[1])
background_file = os.path.join(build_dir, 'background.html')

with open(background_file) as f:
    scripts = re.findall(r'<script src="([^"]+)"></script>', f.read())

if len(scripts) == 0:
    raise SystemExit('No scripts found in background.html.')

# A service worker can't load scripts on demand: the lz4 codecs which
# lz4-block-codec-any.js would otherwise inject must be imported upfront.
lz4_any = 'lib/lz4/lz4-block-codec-any.js'
if lz4_any in scripts:
    i = scripts.index(lz4_any) + 1
    scripts[i:i] = [
        'lib/lz4/lz4-block-codec-wasm.js',
        'lib/lz4/lz4-block-codec-js.js',
    ]

with open(os.path.join(build_dir, 'js', 'sw.js'), 'w') as f:
    f.write('// Generated by tools/make-mv3-sw.py from src/background.html.\n\n')
    f.write("'use strict';\n\n")
    f.write('importScripts(\n')
    f.write(',\n'.join("    '/%s'" % s for s in scripts))
    f.write('\n);\n')

os.remove(background_file)
